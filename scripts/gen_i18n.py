#!/usr/bin/env python3
"""Generate every localized artifact from i18n/strings/*.json + i18n/languages.json.

  strings/_source.json   the 60 English source strings (order is fixed)
  strings/<code>.json    translations, same order
  languages.json         code / autonym / rtl / chrome-extension locale
Outputs: i18n/keyboard_switcher_<code>.ts, src/core/languages_gen.h,
browser-extension/_locales/*, .desktop Comment[..] lines, MSIX <Resource> list.
Languages in ALIASES have no own translation and reuse a close language.
"""
import json, re, pathlib, html
ROOT = pathlib.Path(__file__).resolve().parent.parent
I18N = ROOT / "i18n"
src = json.load(open(I18N / "strings/_source.json", encoding="utf8"))
langs = json.load(open(I18N / "languages.json", encoding="utf8"))
have = {p.stem for p in (I18N / "strings").glob("*.json") if p.stem != "_source"}
ALIASES = {"bho":"hi","mai":"hi","awa":"hi","mag":"hi","mwr":"hi","bgc":"hi","hne":"hi",
           "ctg":"bn","skr":"ur","dcc":"ur","za":"zh_CN","ff":"fr","mad":"id"}
real = [l for l in langs if l["code"] in have or l["code"] == "en"]
for l in langs:
    assert l["code"] in have or l["code"] == "en" or l["code"] in ALIASES, l["code"]
tr = {c: json.load(open(I18N / f"strings/{c}.json", encoding="utf8")) for c in have}

CTX = [("Backend", range(0, 7)), ("SettingsWindow", range(7, 36)), ("TrayApp", range(36, 41)),
       ("SettingsWindow", [41]), ("Presets", range(42, 45)), ("SettingsWindow", range(55, 60))]
def ts(code, t):
    esc = lambda s: html.escape(s, quote=False)
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!DOCTYPE TS>',
           f'<TS version="2.1" language="{code}">']
    for name, idx in CTX:
        out.append(f"<context>\n    <name>{name}</name>")
        for i in idx:
            out.append(f"    <message>\n        <source>{esc(src[i])}</source>\n"
                       f"        <translation>{esc(t[i])}</translation>\n    </message>")
        out.append("</context>")
    out.append("</TS>\n")
    return "\n".join(out)
for old in I18N.glob("keyboard_switcher_*.ts"): old.unlink()
for c, t in tr.items():
    (I18N / f"keyboard_switcher_{c}.ts").write_text(ts(c, t), encoding="utf8")

# C++ table
def cstr(x):  # octal-escaped UTF-8: independent of compiler source charset and C++20 char8_t
    return "".join("\\%03o" % b if b >= 128 else chr(b) for b in x.encode("utf8"))
rows = "\n".join('    {"%s", "%s", %s},  // %s' % (l["code"], cstr(l["autonym"]), "true" if l["rtl"] else "false", l["english"]) for l in real)
al = ",\n".join('    {"%s", "%s"}' % kv for kv in ALIASES.items())
(ROOT / "src/core/languages_gen.h").write_text(
    "// Generated by scripts/gen_i18n.py - do not edit.\n#pragma once\n"
    "struct LangRow { const char *code; const char *name; bool rtl; };\n"
    "struct AliasRow { const char *from; const char *to; };\n"
    f"static const LangRow kLangRows[] = {{\n{rows}\n}};\n"
    f"static const AliasRow kAliasRows[] = {{\n{al}\n}};\n", encoding="utf8")

# browser extension
EXT = {7: None}  # keys: message name -> index
extmap = {"description": 45, "optionsIntro": 46, "optionsPort": 47, "optionsSave": 48, "optionsTest": 49,
          "optionsSaved": 50, "optionsConnected": 51, "optionsNotApp": 52, "optionsNotRunning": 53}
loc = ROOT / "browser-extension/_locales"
import shutil
if loc.exists(): shutil.rmtree(loc)
for l in real:
    ch = l["chrome"]
    if not ch: continue
    t = src if l["code"] == "en" else tr[l["code"]]
    m = {"name": {"message": "Keyboard Switcher"}}
    for k, i in extmap.items(): m[k] = {"message": t[i]}
    d = loc / ch; d.mkdir(parents=True)
    (d / "messages.json").write_text(json.dumps(m, ensure_ascii=False, indent=2) + "\n", encoding="utf8")

# .desktop
p = ROOT / "packaging/linux/io.github.KeyboardSwitcher.desktop"
lines = [x for x in p.read_text(encoding="utf8").splitlines() if not x.startswith(("Comment[", "Name["))]
out = []
for x in lines:
    out.append(x)
    if x.startswith("Comment="):
        for l in real:
            if l["code"] in ("en", "sh"): continue
            out.append(f'Comment[{l["code"]}]={tr[l["code"]][54]}')
p.write_text("\n".join(out) + "\n", encoding="utf8")

# MSIX resources
p = ROOT / "packaging/AppxManifest.xml.in"
s = p.read_text(encoding="utf8")
tags = []
for l in real:
    tag = {"zh_CN": "zh-Hans", "zh_TW": "zh-Hant", "sh": "sr-Latn", "or": "or", "fil": "fil"}.get(l["code"], l["code"].replace("_", "-"))
    tags.append(f'    <Resource Language="{tag}" />')
s = re.sub(r"  <Resources>.*?</Resources>", "  <Resources>\n" + "\n".join(tags) + "\n  </Resources>", s, flags=re.S)
p.write_text(s, encoding="utf8")
print(len(real), "translated languages;", len(ALIASES), "aliases")
